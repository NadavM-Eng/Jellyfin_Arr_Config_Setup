    prowlarr_post "/api/v1/indexerproxy" "$payload"

    info "TRAWL proxy added."
}


# ------------------------------------------------------------------------------
# Run configuration
# ------------------------------------------------------------------------------

printf '\n'
printf '============================================================\n'
printf 'PROWLARR QUICK CONFIGURATION\n'
printf '============================================================\n'

configure_sonarr
configure_radarr
configure_trawl

# INDEXERS creator
INDEXER_BOOTSTRAP="$PROJECT_ROOT/bootstrap/prowlarr/indexers.sh"

[[ -f "$INDEXER_BOOTSTRAP" ]] ||
    fatal "Missing Prowlarr indexer bootstrap: $INDEXER_BOOTSTRAP"

# shellcheck disable=SC1090
source "$INDEXER_BOOTSTRAP"

configure_public_indexers
configure_private_indexers

printf '\n'
printf '============================================================\n'
printf 'PROWLARR CONFIGURATION COMPLETE\n'
printf '============================================================\n'

info "Sonarr: configured"
info "Radarr: configured"
info "TRAWL:  configured"
