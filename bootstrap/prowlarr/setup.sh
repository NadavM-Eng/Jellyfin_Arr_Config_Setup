# ------------------------------------------------------------------------------
# TRAWL
# ------------------------------------------------------------------------------

configure_trawl() {

    if proxy_exists "TRAWL"; then
        info "TRAWL already exists in Prowlarr. Skipping."
        return
    fi

    info "Adding TRAWL proxy to Prowlarr..."

    local payload

    payload="$(cat <<'JSON'
{
  "onHealthIssue": false,
  "supportsOnHealthIssue": false,
  "includeHealthWarnings": false,
  "name": "TRAWL",
  "fields": [
    {
      "name": "host",
      "value": "http://trawl:8191/"
    },
    {
      "name": "requestTimeout",
      "value": 60
    }
  ],
  "implementationName": "FlareSolverr",
  "implementation": "FlareSolverr",
  "configContract": "FlareSolverrSettings",
